import { createClient } from '@supabase/supabase-js';
import { NextResponse } from 'next/server';

// ---------------------------------------------------------------------------
// Admin client setup — same pattern as the close deal route.
// ---------------------------------------------------------------------------
const supabaseUrl =
  process.env.NEXT_PUBLIC_SUPABASE_URL ??
  process.env.SUPABASE_URL;

const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

const jsonError = (message: string, status: number) =>
  NextResponse.json({ error: message }, { status });

function createAdminClient() {
  if (!supabaseUrl || !serviceRoleKey) {
    throw new Error(
      'Missing Supabase server environment. Configure SUPABASE_SERVICE_ROLE_KEY and the Supabase URL.',
    );
  }
  return createClient(supabaseUrl, serviceRoleKey, {
    auth: { autoRefreshToken: false, persistSession: false },
  });
}

async function resolveActingUser(admin: ReturnType<typeof createAdminClient>, request: Request) {
  const authHeader = request.headers.get('authorization');
  if (!authHeader?.startsWith('Bearer ')) return null;

  const token = authHeader.slice('Bearer '.length).trim();
  const { data: { user }, error } = await admin.auth.getUser(token);
  if (error || !user) return null;
  return user;
}

// ---------------------------------------------------------------------------
// GET /api/agency/invitations
// Returns all pending invitations for the acting owner's agency.
// ---------------------------------------------------------------------------
export async function GET(request: Request) {
  let admin;
  try { admin = createAdminClient(); }
  catch (e) { return jsonError(e instanceof Error ? e.message : 'Server error.', 500); }

  const user = await resolveActingUser(admin, request);
  if (!user) return jsonError('Unauthorized.', 401);

  // Resolve acting user's agency and confirm they are the owner.
  const { data: membership, error: membershipError } = await admin
    .from('agency_memberships')
    .select('agency_id, role')
    .eq('user_id', user.id)
    .maybeSingle();

  if (membershipError) return jsonError(membershipError.message, 500);
  if (!membership)     return jsonError('You do not belong to an agency.', 403);
  if (membership.role !== 'owner') return jsonError('Only agency owners can view invitations.', 403);

  const { data: invitations, error: invitationsError } = await admin
    .from('agency_invitations')
    .select('*')
    .eq('agency_id', membership.agency_id)
    .eq('status', 'pending')
    .order('created_at', { ascending: false });

  if (invitationsError) return jsonError(invitationsError.message, 500);

  return NextResponse.json({ invitations: invitations ?? [] });
}

// ---------------------------------------------------------------------------
// POST /api/agency/invitations
// Creates a new pending invitation for the given email.
//
// Body: { email: string }
//
// Rules:
// - Acting user must be an agency owner.
// - invited_email must not already be a member of the agency.
// - Only one pending invite per email per agency (DB unique index enforces this).
// - The token is generated by the DB default (gen_random_bytes).
// - The owner copies the resulting invite link manually.
//
// FUTURE: To send automatic emails, call
//   admin.auth.admin.inviteUserByEmail({ email, data: { token, agency_id } })
//   here instead of (or in addition to) the manual token return. No schema
//   change is required. See migration 007 comments for the full upgrade path.
// ---------------------------------------------------------------------------
export async function POST(request: Request) {
  let admin;
  try { admin = createAdminClient(); }
  catch (e) { return jsonError(e instanceof Error ? e.message : 'Server error.', 500); }

  const user = await resolveActingUser(admin, request);
  if (!user) return jsonError('Unauthorized.', 401);

  // Confirm owner role.
  const { data: membership, error: membershipError } = await admin
    .from('agency_memberships')
    .select('agency_id, role')
    .eq('user_id', user.id)
    .maybeSingle();

  if (membershipError) return jsonError(membershipError.message, 500);
  if (!membership)     return jsonError('You do not belong to an agency.', 403);
  if (membership.role !== 'owner') return jsonError('Only agency owners can invite members.', 403);

  const body = await request.json().catch(() => null);
  const email = typeof body?.email === 'string' ? body.email.trim().toLowerCase() : '';

  if (!email || !email.includes('@')) {
    return jsonError('A valid email address is required.', 422);
  }

  // Reject if this email is already a member of the agency.
  // We check via auth.users join — but we only have agency_memberships with user_id.
  // We cannot easily query by email in agency_memberships without a profiles table.
  // Instead, look up the auth user by email and check membership.
  const { data: existingUsers } = await admin.auth.admin.listUsers();
  const matchedUser = existingUsers?.users?.find(
    (u) => u.email?.toLowerCase() === email,
  );

  if (matchedUser) {
    const { data: existingMembership } = await admin
      .from('agency_memberships')
      .select('id')
      .eq('agency_id', membership.agency_id)
      .eq('user_id', matchedUser.id)
      .maybeSingle();

    if (existingMembership) {
      return jsonError('This person is already a member of your agency.', 409);
    }
  }

  // Insert the invitation row. The DB generates the token and expires_at.
  const { data: invitation, error: insertError } = await admin
    .from('agency_invitations')
    .insert({
      agency_id:     membership.agency_id,
      invited_by:    user.id,
      invited_email: email,
      role:          'agent',
    })
    .select()
    .single();

  if (insertError) {
    // Unique index violation = duplicate pending invite for this email.
    if (insertError.code === '23505') {
      return jsonError('A pending invitation already exists for this email address.', 409);
    }
    return jsonError(insertError.message, 500);
  }

  return NextResponse.json({ invitation }, { status: 201 });
}